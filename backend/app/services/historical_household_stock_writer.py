"""Maintenance-admitted, transaction-owned automatic historical stock bootstrap.

No client endpoint and no confirmation UI. A fresh household with no current
stock may derive its opening inventory from proven historical receipts. The
same owned baseline may be recalculated as more older receipts are imported,
but *any* other inventory/event history blocks retroactive stock mutation.
"""
from __future__ import annotations

from datetime import datetime, timezone
import json
from uuid import uuid4

from sqlalchemy import bindparam, text

from app.services.canonical_inventory_identity_service import (
    apply_inventory_purchase_by_identity,
    ensure_locationless_inventory_identity_guard,
)
from app.services.historical_household_stock_source import (
    load_automatic_historical_stock,
)

MAX_AUTO_STOCK_PER_ARTICLE = 1000000
SOURCE = "historical_auto_stock"


def _locked_cutover(conn, owner: str):
    return conn.execute(text("""
        SELECT first_current_purchase_date
        FROM household_receipt_history_cutovers
        WHERE household_id = :household_id
        FOR UPDATE
    """), {"household_id": owner}).scalar_one_or_none()


def _owned_baselines(conn, owner: str) -> dict:
    rows = conn.execute(text("""
        SELECT household_article_id, inventory_id, inventory_event_id,
               quantity, source_fingerprint, first_current_purchase_date
        FROM household_historical_auto_stock_baselines
        WHERE household_id = :household_id
    """), {"household_id": owner}).mappings().all()
    return {str(r["household_article_id"]): dict(r) for r in rows}


def _block_existing_business_history(conn, owner, members) -> bool:
    """Both event history AND old stock rows must be generated by this owner."""
    outside_events = conn.execute(text("""
        SELECT 1
        FROM inventory_events e
        LEFT JOIN household_historical_auto_stock_baselines b
          ON b.household_id = e.household_id
         AND b.household_article_id = e.household_article_id
         AND b.inventory_event_id = e.id
        WHERE e.household_id = :household_id
          AND (e.household_article_id = ANY(:article_ids)
               OR e.article_id = ANY(:article_ids))
          AND b.inventory_event_id IS NULL
        LIMIT 1
    """), {"household_id": owner, "article_ids": list(members)}).scalar_one_or_none()
    if outside_events is not None:
        return True
    outside_stock = conn.execute(text("""
        SELECT 1
        FROM inventory i
        LEFT JOIN household_historical_auto_stock_baselines b
          ON b.household_id = i.household_id
         AND b.household_article_id = i.household_article_id
         AND b.inventory_id = i.id
        WHERE i.household_id = :household_id
          AND i.household_article_id = ANY(:article_ids)
          AND b.inventory_id IS NULL
        LIMIT 1
    """), {"household_id": owner, "article_ids": list(members)}).scalar_one_or_none()
    return outside_stock is not None


def _lock_owned_article(conn, owner: str, article_id: str) -> dict | None:
    row = conn.execute(text("""
        SELECT id, naam
        FROM household_articles
        WHERE household_id = :household_id
          AND id = :article_id
          AND COALESCE(status, 'active') = 'active'
        FOR UPDATE
    """), {"household_id": owner, "article_id": article_id}).mappings().first()
    return dict(row) if row else None


def _existing_baseline_stock(conn, owner: str, article_id: str, baseline: dict):
    rows = conn.execute(text("""
        SELECT id, aantal, space_id, sublocation_id
        FROM inventory
        WHERE household_id=:household_id AND household_article_id=:article_id
        ORDER BY id FOR UPDATE
    """), {"household_id": owner, "article_id": article_id}).mappings().all()
    expected_inventory = str(baseline.get("inventory_id") or "")
    expected_qty = int(baseline["quantity"])
    if expected_qty == 0 and expected_inventory == "" and not rows:
        return None
    if (len(rows) != 1 or str(rows[0]["id"]) != expected_inventory
            or rows[0].get("space_id") is not None
            or rows[0].get("sublocation_id") is not None
            or int(rows[0]["aantal"]) != expected_qty):
        raise ValueError("Automatische historische voorraad wijkt af van bewaarde baseline")
    return rows[0]


def _write_baseline_event(conn, *, owner, article_id, name, qty, cutoff, event_id):
    occurred = str(cutoff)[:10] + "T00:00:00+00:00"
    now = datetime.now(timezone.utc).isoformat()
    conn.execute(text("""
        INSERT INTO inventory_events (
            id, household_id, article_id, household_article_id, article_name,
            location_id, location_label, event_type, quantity, old_quantity,
            new_quantity, source, note, effective_at, recorded_at,
            effective_at_precision, event_priority, source_reference, created_at
        ) VALUES (
            :event_id, :household_id, :article_id, :article_id, :article_name,
            NULL, NULL, 'baseline', :quantity, 0,
            :quantity, :source, :note, :effective_at, :recorded_at,
            'date', 0, :reference, CURRENT_TIMESTAMP
        )
    """), {
        "event_id": event_id, "household_id": owner, "article_id": article_id,
        "article_name": name, "quantity": qty, "source": SOURCE,
        "note": "Automatische beginvoorraad op basis van historische kassabonnen en huishoudinstellingen",
        "effective_at": occurred, "recorded_at": now,
        "reference": "historical-auto:" + owner + ":" + article_id,
    })


def _create_baseline(conn, *, owner, article_id, article_name, qty,
                     fingerprint, cutoff):
    event_id = uuid4().hex
    inventory_id = None
    if qty > 0:
        inventory_id = apply_inventory_purchase_by_identity(
            conn, household_id=owner, household_article_id=article_id,
            quantity=qty, space_id=None, sublocation_id=None,
        )
    _write_baseline_event(
        conn, owner=owner, article_id=article_id, name=article_name,
        qty=qty, cutoff=cutoff, event_id=event_id,
    )
    conn.execute(text("""
        INSERT INTO household_historical_auto_stock_baselines (
            household_id, household_article_id, inventory_id,
            inventory_event_id, quantity, source_fingerprint,
            first_current_purchase_date, updated_at
        ) VALUES (
            :household_id, :article_id, :inventory_id,
            :event_id, :quantity, :fingerprint, :cutover, CURRENT_TIMESTAMP
        )
    """), {
        "household_id": owner, "article_id": article_id,
        "inventory_id": inventory_id, "event_id": event_id,
        "quantity": qty, "fingerprint": fingerprint, "cutover": cutoff,
    })


def _revise_baseline(conn, *, owner, article_id, qty, baseline, fingerprint, cutoff):
    stored_id = str(baseline["inventory_event_id"])
    # The event's trusted identity must still be exactly our own baseline.
    event = conn.execute(text("""
        SELECT id, source, event_type, quantity, effective_at
        FROM inventory_events
        WHERE household_id=:household_id
          AND household_article_id=:article_id
          AND id=:event_id
        FOR UPDATE
    """), {"household_id": owner, "article_id": article_id, "event_id": stored_id}).mappings().first()
    if (not event or event["source"] != SOURCE or event["event_type"] != "baseline"
            or int(event["quantity"]) != int(baseline["quantity"])
            or str(event["effective_at"])[:10] != str(cutoff)[:10]):
        raise ValueError("Automatische baseline is niet meer intact")
    stock = _existing_baseline_stock(conn, owner, article_id, baseline)
    previous = int(baseline["quantity"])
    inventory_id = str(baseline.get("inventory_id") or "") or None
    if qty != previous:
        changed = conn.execute(text("""
            UPDATE inventory_events
            SET quantity=:quantity, new_quantity=:quantity
            WHERE id=:event_id AND household_id=:household_id
              AND household_article_id=:article_id
              AND source=:source AND event_type='baseline'
        """), {
            "quantity": qty, "event_id": stored_id, "household_id": owner,
            "article_id": article_id, "source": SOURCE,
        })
        if changed.rowcount != 1:
            raise ValueError("Historische baseline kon niet atomair worden aangepast")
        if stock is not None and qty == 0:
            deleted = conn.execute(text("""
                DELETE FROM inventory
                WHERE id=:inventory_id AND household_id=:household_id
                  AND household_article_id=:article_id
                  AND space_id IS NULL AND sublocation_id IS NULL
            """), {
                "inventory_id": inventory_id, "household_id": owner,
                "article_id": article_id,
            })
            if deleted.rowcount != 1:
                raise ValueError("Locatievrije baselinevoorraad ontbreekt")
            inventory_id = None
        elif stock is not None:
            changed = conn.execute(text("""
                UPDATE inventory SET aantal=:quantity, updated_at=CURRENT_TIMESTAMP
                WHERE id=:inventory_id AND household_id=:household_id
                  AND household_article_id=:article_id
                  AND space_id IS NULL AND sublocation_id IS NULL
                  AND aantal=:previous
            """), {
                "quantity": qty, "previous": previous, "inventory_id": inventory_id,
                "household_id": owner, "article_id": article_id,
            })
            if changed.rowcount != 1:
                raise ValueError("Voorraad is tussentijds gewijzigd")
        elif qty > 0:
            # Baseline event already records qty. The canonical purchase writer
            # reconciles temporal history against the new target in this case.
            inventory_id = apply_inventory_purchase_by_identity(
                conn, household_id=owner, household_article_id=article_id,
                quantity=qty, space_id=None, sublocation_id=None,
            )
    changed = conn.execute(text("""
        UPDATE household_historical_auto_stock_baselines
        SET quantity=:quantity, inventory_id=:inventory_id,
            source_fingerprint=:fingerprint, updated_at=CURRENT_TIMESTAMP
        WHERE household_id=:household_id AND household_article_id=:article_id
          AND inventory_event_id=:event_id
    """), {
        "quantity": qty, "inventory_id": inventory_id,
        "fingerprint": fingerprint, "household_id": owner,
        "article_id": article_id, "event_id": stored_id,
    })
    if changed.rowcount != 1:
        raise ValueError("Historische voorraadregistratie kon niet worden bijgewerkt")


def _sync_historical_purchase_cadences(conn, *, owner: str, calculated: dict) -> dict:
    """Store trusted cadence per matched article, including all synonym members.

    The cadence is metadata, never an inventory event. Invalidated historic
    sources remove only this service's own projection, not current purchase
    history or a manually configured minimum-stock threshold.
    """
    rows = calculated.get("purchase_cadences") or {}
    source_fingerprint = str(calculated.get("source_fingerprint") or "").strip()
    if len(source_fingerprint) != 64:
        raise ValueError("Historisch koopritme mist bronfingerprint")
    written = 0
    for article_id, result in sorted(rows.items()):
        if article_id not in (result.get("matched_and_synonyms") or []):
            raise ValueError("Koopritme hoort niet bij het gekoppelde huishoudartikel")
        interval = result["average_repurchase_interval_days"]
        if not (0 < float(interval) <= 3650 and int(result["purchase_day_count"]) >= 3):
            raise ValueError("Onvoldoende koopritmebewijs")
        affected = conn.execute(text("""
            INSERT INTO household_historical_purchase_cadences (
                household_id, household_article_id, average_repurchase_interval_days,
                purchase_day_count, first_purchase_date, last_purchase_date,
                matched_and_synonyms, source_fingerprint, updated_at
            ) VALUES (
                :household_id, :article_id, :interval,
                :day_count, :first_day, :last_day,
                :members, :fingerprint, CURRENT_TIMESTAMP
            )
            ON CONFLICT (household_id, household_article_id) DO UPDATE
            SET average_repurchase_interval_days=excluded.average_repurchase_interval_days,
                purchase_day_count=excluded.purchase_day_count,
                first_purchase_date=excluded.first_purchase_date,
                last_purchase_date=excluded.last_purchase_date,
                matched_and_synonyms=excluded.matched_and_synonyms,
                source_fingerprint=excluded.source_fingerprint,
                updated_at=CURRENT_TIMESTAMP
            WHERE household_historical_purchase_cadences.source_fingerprint
                  IS DISTINCT FROM excluded.source_fingerprint
               OR household_historical_purchase_cadences.average_repurchase_interval_days
                  IS DISTINCT FROM excluded.average_repurchase_interval_days
        """), {
            "household_id": owner, "article_id": article_id,
            "interval": interval, "day_count": int(result["purchase_day_count"]),
            "first_day": result["first_purchase_date"],
            "last_day": result["last_purchase_date"],
            "members": json.dumps(sorted(result["matched_and_synonyms"])),
            "fingerprint": source_fingerprint,
        })
        written += int(affected.rowcount or 0)
    # A changed synonym link or removed historical receipt invalidates stale
    # projections: remove solely our derived cadence rows for this household.
    if rows:
        removed = conn.execute(text("""
            DELETE FROM household_historical_purchase_cadences
            WHERE household_id=:household_id
              AND household_article_id NOT IN :article_ids
        """).bindparams(bindparam("article_ids", expanding=True)), {
            "household_id": owner, "article_ids": list(rows),
        })
    else:
        removed = conn.execute(text("""
            DELETE FROM household_historical_purchase_cadences
            WHERE household_id=:household_id
        """), {"household_id": owner})
    return {"cadences_written": written, "cadences_expired": int(removed.rowcount or 0)}


def refresh_automatic_historical_stock(conn, *, household_id: str) -> dict:
    """ONE writer-operation transaction. No global session or browser identity.

    The worker derives household_id only from persistent cutover rows. Locks
    prevent two concurrent background calculations for the same household.
    This is not a backfill action for pre-existing legacy stock.
    """
    owner = str(household_id or "").strip()
    if not owner or owner == "0":
        raise ValueError("Historische automatische voorraad vereist regulier huishouden")
    cutoff = _locked_cutover(conn, owner)
    if cutoff is None:
        return {"status": "legacy_untouched", "created": 0, "revised": 0, "skipped": 0}

    calculated = load_automatic_historical_stock(conn, household_id=owner)
    if calculated.get("status") != "calculated":
        return {"status": "not_ready", "created": 0, "revised": 0, "skipped": 0}
    quantities = calculated["quantities"]
    if not quantities:
        cadence = _sync_historical_purchase_cadences(
            conn, owner=owner, calculated=calculated,
        )
        return {"status": "no_trusted_matches", "created": 0, "revised": 0,
                "skipped": 0, "excluded_rows": calculated.get("excluded_untrusted_rows", 0),
                **cadence}

    baseline = _owned_baselines(conn, owner)
    group_by_article = calculated.get("synonym_groups") or {}
    # Grouped records must be all-or-none; another current event from a
    # confirmed synonym cannot be treated as unused old stock.
    components = {}
    for article_id in quantities:
        members = tuple(sorted(group_by_article.get(article_id) or (article_id,)))
        components.setdefault(members, set()).add(article_id)

    ensure_locationless_inventory_identity_guard(conn)
    created = revised = skipped = unchanged = 0
    fingerprint = str(calculated["source_fingerprint"])
    for members, active_articles in sorted(components.items()):
        if any(quantities[a] > MAX_AUTO_STOCK_PER_ARTICLE or quantities[a] < 0
               for a in active_articles):
            skipped += len(active_articles)
            continue
        owned = [_lock_owned_article(conn, owner, member) for member in members]
        if any(row is None for row in owned):
            skipped += len(active_articles)
            continue
        if _block_existing_business_history(conn, owner, members):
            skipped += len(active_articles)
            continue
        for article_id in sorted(active_articles):
            current = baseline.get(article_id)
            qty = int(quantities[article_id])
            row = next(row for row in owned if str(row["id"]) == article_id)
            if current is None:
                _create_baseline(
                    conn, owner=owner, article_id=article_id,
                    article_name=str(row["naam"]), qty=qty,
                    fingerprint=fingerprint, cutoff=cutoff,
                )
                created += 1
            elif current["source_fingerprint"] == fingerprint and int(current["quantity"]) == qty:
                unchanged += 1
            else:
                _revise_baseline(
                    conn, owner=owner, article_id=article_id, qty=qty,
                    baseline=current, fingerprint=fingerprint, cutoff=cutoff,
                )
                revised += 1
    cadence = _sync_historical_purchase_cadences(
        conn, owner=owner, calculated=calculated,
    )
    return {
        "status": "applied", "created": created, "revised": revised,
        "unchanged": unchanged, "skipped": skipped,
        "excluded_rows": calculated.get("excluded_untrusted_rows", 0),
        **cadence,
    }
