"""Maintenance-admitted, transaction-owned automatic historical stock bootstrap.

No client endpoint and no confirmation UI. A fresh household with no current
stock may derive its opening inventory from proven historical receipts. The
same owned baseline may be recalculated as more older receipts are imported,
but *any* other inventory/event history blocks retroactive stock mutation.
"""
